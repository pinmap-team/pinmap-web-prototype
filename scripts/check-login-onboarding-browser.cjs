const {chromium}=require(process.env.PINMAP_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const origin=process.env.PINMAP_BROWSER_ORIGIN||'http://127.0.0.1:8093';
assert.equal(new URL(origin).hostname,'127.0.0.1');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.PINMAP_CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const results=[];
 for(const viewport of [{width:402,height:874},{width:1440,height:960}]){
  const page=await browser.newPage({viewport});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/auth-client.js*',r=>r.fulfill({contentType:'text/javascript',body:`(()=>{const user={id:'qa-user',email:'qa@example.com',user_metadata:JSON.parse(localStorage.getItem('qa-metadata')||'{}')};const current=()=>localStorage.getItem('pinmap.auth.v1')?user:null;const client={auth:{initialize:async()=>({error:null}),getSession:async()=>({data:{session:current()?{user,access_token:'qa-token'}:null},error:null}),getUser:async()=>({data:{user:current()},error:null}),updateUser:async({data})=>{Object.assign(user.user_metadata,data);localStorage.setItem('qa-metadata',JSON.stringify(user.user_metadata));return {data:{user},error:null}},onAuthStateChange:()=>({data:{subscription:{unsubscribe(){}}}})}};window.PinmapAuth={ready:async()=>client,verifiedUser:async()=>({data:{user:current()},error:null}),login:()=>{},message:e=>e?.message||'오류'};})();`}));
  await page.route('**/api/content-save*',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({items:[],next_offset:null})}));
  await page.route('**/api/map-config',r=>r.fulfill({status:200,contentType:'application/json',body:'{}'}));
  await page.goto(origin+'/auth.html?screen=welcome');
  await page.locator('#auth-main[data-screen="intro"]').waitFor();
  assert.equal(await page.locator('.auth-brand').evaluate(el=>el.tagName),'SPAN');
  assert.equal(await page.locator('.auth-brand[href]').count(),0);
  await page.locator('#auth-main[data-screen="welcome"]').waitFor({timeout:5000});
  assert.equal(await page.locator('.auth-hero:visible').count(),0);
  await page.evaluate(()=>localStorage.setItem('pinmap.auth.v1','qa-token'));
  await page.goto(origin+'/index.html');
  const frame=page.frameLocator('.phone-frame');
  await frame.locator('#onboarding').waitFor({timeout:15000});
  assert.equal(await frame.locator('#auth-gate').count(),0);
  assert.equal(await frame.locator('#onboarding .ob-screen.step2').count(),1);
  assert.equal(await frame.locator('#onboarding .ob-splash').count(),0);
  await frame.locator('[data-ob="skip"]').click();
  await frame.locator('#coach').waitFor({timeout:5000});
  assert.match(await frame.locator('#coach').innerText(),/첫 콘텐츠 저장하기/);
  await frame.locator('[data-coach="next"]').click();
  assert.match(await frame.locator('#coach').innerText(),/콘텐츠 추가하기/);
  await frame.locator('[data-coach="skip"]').click();
  await page.reload();
  await page.waitForURL(/auth\.html\?screen=welcome/);
  await page.locator('#auth-main[data-screen="welcome"]').waitFor({timeout:5000});
  assert.equal(await page.evaluate(()=>localStorage.getItem('pinmap.auth.v1')),null);
  assert.equal(await page.locator('[data-auth="signin"]').count(),1);
  await page.evaluate(()=>localStorage.setItem('pinmap.auth.v1','qa-token'));
  await page.goto(origin+'/index.html');
  await frame.locator('.bottomnav').waitFor({timeout:15000});
  await page.waitForTimeout(500);
  assert.equal(await frame.locator('#onboarding').count(),0);
  await frame.locator('.bottomnav [data-page="my"]').click();
  await frame.locator('[data-action="guide"]').click();
  await frame.locator('[data-action="howto"]').click();
  assert.equal(await frame.locator('.mypage.howtopage').count(),1);
  await frame.locator('.howtopage [data-action="linkimport"]').click();
  assert.equal(await frame.locator('#sheet.add-import-sheet[open]').count(),1);
  await frame.locator('#sheet').evaluate(el=>el.close());
  await frame.locator('.howtopage [data-page="guide"]').click();
  await frame.locator('[data-action="coachagain"]').click();
  await frame.locator('#coach').waitFor({timeout:5000});
  await frame.locator('#coach [data-coach="exit"]').click();
  assert.equal(await frame.locator('.mypage').locator('h1').innerText(),'이용 가이드');
  await frame.locator('.mypage [data-action="intro"]').click();
  await frame.locator('#onboarding .ob-skip[data-ob="exit"]').waitFor({timeout:5000});
  assert.equal(await frame.locator('#onboarding .ob-screen.step2').count(),1);
  assert.equal(await frame.locator('#onboarding .ob-splash').count(),0);
  await frame.locator('#onboarding [data-ob="exit"]').click();
  assert.equal(await frame.locator('.mypage').locator('h1').innerText(),'이용 가이드');
  await page.goto(origin+'/index.html?mode=prototype');
  await page.waitForURL(/auth\.html\?screen=welcome/);
  assert.deepEqual(errors,[]);
  results.push({viewport,errors});
  await page.close();
 }
 console.log(JSON.stringify(results));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
